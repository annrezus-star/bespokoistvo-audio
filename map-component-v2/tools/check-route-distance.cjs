const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.join(__dirname, '..');
const context = {window: {}};
vm.runInNewContext(fs.readFileSync(path.join(root, 'route.js'), 'utf8'), context);
const create = context.window.BespokoistvoRoute.createNavigation;
const geometry = coordinates => ({type: 'FeatureCollection', features: [{type: 'Feature', properties: {}, geometry: {type: 'LineString', coordinates}}]});
const stops = [{id: 'start', coordinates: [0, 0]}, {id: 'end', coordinates: [0, .001]}];
const u = create(geometry([[0, 0], [.001, 0], [.001, .001], [0, .001]]), stops);
const full = u.measure(1);
assert(Math.abs(full.distanceMeters - 333.58524) < .01, 'U-shaped walking route is about 334 m, not its 111 m chord');
assert.equal(full.remainingMeters, null, 'No GPS cannot give remaining distance from a person');
const midway = u.measure(1, {coordinates: [.001, .0005], accuracy: 5});
assert.equal(midway.mode, 'remaining');
assert(Math.abs(midway.remainingMeters - 166.79262) < .01);
assert(Math.abs(midway.estimatedMinutes - 2.50189) < .001);
assert.equal(u.measure(1, {coordinates: [0, .001], accuracy: 5}).mode, 'at-approach');
assert.equal(u.measure(1, {coordinates: [0, .001], accuracy: 150}).mode, 'imprecise');
assert.equal(u.measure(1, {coordinates: [1, 1], accuracy: 5}).mode, 'off-route');
assert.equal(u.measure(1, {coordinates: [1, 1], accuracy: 5}).remainingMeters, null);
assert.equal(u.measure(0).distanceMeters, null, 'No invented walking route to the initial stop');
assert.equal(u.measure(0, {coordinates: [0, 0], accuracy: 5}).mode, 'at-start');
assert.equal(u.measure(2).completed, true);
assert.throws(() => u.measure(-1), /остановка/);
const backtrack = create(geometry([[0, 0], [.002, 0], [0, 0], [0, .001]]), stops);
assert.equal(backtrack.measure(1, {coordinates: [.001, 0], accuracy: 5}).mode, 'ambiguous', 'Retraced geometry cannot silently invent progress');
assert.equal(backtrack.measure(1, {coordinates: [.001, 0], accuracy: 5}).remainingMeters, null);
vm.runInNewContext(fs.readFileSync(path.join(root, 'stops.js'), 'utf8'), context);
const actual = JSON.parse(fs.readFileSync(path.join(root, 'route.geojson'))), before = JSON.stringify(actual);
const real = create(actual, context.window.BespokoistvoStops);
const lengths = actual.features.map((feature, i) => {
  const step = real.measure(i + 1);
  assert(step.distanceMeters > 0 && Number.isFinite(step.estimatedMinutes));
  assert.equal(step.targetStopId, feature.properties.to);
  assert.equal(step.fromStopId, feature.properties.from);
  assert.equal(real.geometryFor(i + 1), feature);
  return Math.round(step.distanceMeters);
});
assert.equal(JSON.stringify(actual), before, 'Original route geometry remains untouched');
console.log('PASS walking distance vs chord; mid-leg progress; ETA; arrival; poor GPS; outside; ambiguous backtracking; initial/finish; real seven ordered legs (metres):', lengths);
